// The site's only server code. It runs first for every request
// (`assets.run_worker_first: true` in wrangler.jsonc): www.album.guide gets a
// 301 to album.guide, /api/* goes to `routes` below (anything else under /api/*
// is a JSON 404), and every other path is served from dist/ by ASSETS, which
// also answers unknown paths with 404.html.
import { withSecurityHeaders } from './security-headers';
import { SENTRY_TUNNEL_PATH, sentryTunnel } from './sentry';
import { dataPoint, EVENT_PATH, MAX_BODY_BYTES, parseEvent, shouldDrop, visitorHash } from './telemetry';

// Bindings from wrangler.jsonc, typed here rather than generated by
// `wrangler types`: there are only three. ASSETS is the static build. The
// telemetry two are optional so a missing one means "write nothing", never an
// error: TELEMETRY_SALT is unset until JJ adds it (docs/open-items.md), and a
// visitor hash must never use an empty salt.
export interface Env {
  ASSETS: Fetcher;
  EVENTS?: { writeDataPoint(point: ReturnType<typeof dataPoint>): void };
  TELEMETRY_SALT?: string;
}

type CfRequest = Request & { cf?: { country?: string; region?: string; city?: string } };

// POST /api/event: validates, then writes one data point to Analytics Engine
// (standards/telemetry.md). Anything dropped still gets a 204, so a blocked or
// bot request looks the same as a counted one.
export async function recordEvent(request: CfRequest, env: Env): Promise<Response> {
  if (request.headers.get('sec-fetch-site') !== 'same-origin') return new Response(null, { status: 403 });
  if (Number(request.headers.get('content-length') ?? 0) > MAX_BODY_BYTES) return new Response(null, { status: 413 });
  const event = parseEvent(await request.text());
  if (!event) return new Response(null, { status: 400 });

  const userAgent = request.headers.get('user-agent') ?? '';
  if (shouldDrop(userAgent, request.headers.get('sec-gpc'))) return new Response(null, { status: 204 });
  if (!env.EVENTS || !env.TELEMETRY_SALT) return new Response(null, { status: 204 });

  try {
    const ip = request.headers.get('cf-connecting-ip') ?? '';
    env.EVENTS.writeDataPoint(
      dataPoint(event, {
        hostname: new URL(request.url).hostname,
        country: request.cf?.country ?? '',
        region: request.cf?.region ?? '',
        city: request.cf?.city ?? '',
        userAgent,
        visitor: await visitorHash(env.TELEMETRY_SALT, new Date(), ip, userAgent),
      }),
    );
  } catch (error) {
    console.error(
      JSON.stringify({ message: 'telemetry write failed', error: error instanceof Error ? error.message : String(error) }),
    );
  }
  return new Response(null, { status: 204 });
}

type Route = { method: string; path: string; handle: (request: Request, env: Env) => Promise<Response> };

// One entry per /api/* route. Add new ones here.
const routes: Route[] = [
  { method: 'POST', path: EVENT_PATH, handle: recordEvent },
  // Browser error events, forwarded to Sentry (worker/sentry.ts).
  { method: 'POST', path: SENTRY_TUNNEL_PATH, handle: sentryTunnel },
];

// Every response, the redirect and the API's included, gets the security
// headers (worker/security-headers.ts); public/_headers sets the same ones on
// static files.
export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    return withSecurityHeaders(await handle(request, env));
  },
} satisfies ExportedHandler<Env>;

async function handle(request: Request, env: Env): Promise<Response> {
  const url = new URL(request.url);
  if (url.hostname === 'www.album.guide') {
    url.protocol = 'https:';
    url.hostname = 'album.guide';
    return Response.redirect(url.toString(), 301);
  }
  const { pathname } = url;
  if (pathname !== '/api' && !pathname.startsWith('/api/')) return env.ASSETS.fetch(request);
  const route = routes.find((r) => r.method === request.method && r.path === pathname);
  if (route) return route.handle(request, env);
  console.log(JSON.stringify({ message: 'api not found', method: request.method, pathname }));
  return Response.json({ error: 'not found' }, { status: 404 });
}
